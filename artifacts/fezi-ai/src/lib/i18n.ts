export type TranslationKey = keyof typeof dict.en;

export function useTranslation() {
  const appSettings = useLocalStore((s) => s.appSettings);
  const language = appSettings?.language || 'en';
  const isRtl = language === 'fa';
  
  return {
    t: (key: TranslationKey, params?: Record<string, string>) => {
      let str = dict[language]?.[key] || dict.en[key] || key;
      if (params) {
        Object.entries(params).forEach(([k, v]) => {
          str = str.replace(`{${k}}`, v);
        });
      }
      return str;
    },
    lang: language,
    isRtl
  };
}

// Helper to localize API content on the frontend
export function useApiLocalization() {
  const { isRtl, t } = useTranslation();
  const agentTitleKeys: Record<string, TranslationKey> = {
    fezi: 'agent_title_fezi',
    monicah: 'agent_title_monicah',
    arvin: 'agent_title_arvin',
    arta: 'agent_title_arta',
    negar: 'agent_title_negar',
  };
  const planDescriptionKeys: Record<string, TranslationKey> = {
    free: 'plan_desc_free',
    rider: 'plan_desc_rider',
    'swift-rider': 'plan_desc_swift_rider',
    'horse-runner': 'plan_desc_horse_runner',
    'lone-rider': 'plan_desc_lone_rider',
    sovereign: 'plan_desc_sovereign',
  };
  const cadenceKeys: Record<string, TranslationKey> = {
    forever: 'bill_cadence_forever',
    month: 'bill_cadence_month',
    lifetime: 'bill_cadence_lifetime',
  };
  const activityKeys: Record<string, { detail: TranslationKey; time: TranslationKey }> = {
    a1: { detail: 'activity_visual_opened', time: 'activity_12_minutes' },
    a2: { detail: 'activity_story_completed', time: 'activity_42_minutes' },
    a3: { detail: 'activity_quality_passed', time: 'activity_1_hour' },
  };

  return {
    getAgentSpecialty: (agent: any) => {
      if (!agent) return '';
      if (isRtl && agentTitleKeys[agent.id]) return t(agentTitleKeys[agent.id]);
      return agent.title;
    },
    getAgentDescription: (agent: any) => {
      if (!agent) return '';
      if (isRtl && agent.personality?.roleFa) {
        return agent.personality.roleFa;
      }
      return agent.personality?.roleEn || agent.description;
    },
    getPlanName: (plan: any) => {
      if (!plan) return '';
      return isRtl ? (plan.nameFa || plan.name) : plan.name;
    },
    getPlanDescription: (plan: any) => {
      if (!plan) return '';
      return isRtl && planDescriptionKeys[plan.id] ? t(planDescriptionKeys[plan.id]) : plan.description;
    },
    getPlanCadence: (plan: any) => {
      if (!plan) return '';
      return isRtl && cadenceKeys[plan.cadence] ? t(cadenceKeys[plan.cadence]) : plan.cadence;
    },
    getDashboardPlan: (planName: string) => {
      if (!planName) return t('dash_founding');
      if (planName.toLowerCase().includes('founding') && isRtl) return t('dash_founding');
      return planName; // Fallback
    },
    getDashboardGuardian: (status: string) => {
      if (!status) return t('dash_active');
      if (status.toLowerCase().includes('active') && isRtl) return t('dash_active');
      if (status.toLowerCase().includes('monitoring') && isRtl) return t('dash_monitoring');
      return status; // Fallback
    },
    getDashboardActivityDetail: (activity: any) =>
      isRtl && activityKeys[activity?.id] ? t(activityKeys[activity.id].detail) : activity?.detail ?? '',
    getDashboardActivityTime: (activity: any) =>
      isRtl && activityKeys[activity?.id] ? t(activityKeys[activity.id].time) : activity?.time ?? '',
    getPaymentAmount: (amount: string) =>
      isRtl && amount === 'Live rate unavailable' ? t('bill_rate_unavailable') : amount,
    getPaymentWarning: (warning?: string) =>
      isRtl ? t('bill_network_warning') : (warning || t('bill_network_warning')),
  };
}

export function useLanguageEffect() {
  const appSettings = useLocalStore((s) => s.appSettings);
  const language = appSettings?.language || 'en';
  const { accent, theme } = useLocalStore((s) => s.personalization) || { accent: '43 68% 60%', theme: 'dark' };
  
  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'fa' ? 'rtl' : 'ltr';

    const applyTheme = () => {
      const resolvedTheme = theme === 'light' ? 'light' : 'dark';
      document.documentElement.classList.toggle('dark', resolvedTheme === 'dark');
      document.documentElement.style.colorScheme = resolvedTheme;

      const variables = resolvedTheme === 'light'
        ? {
            '--background': '210 25% 97%',
            '--foreground': '222 25% 12%',
            '--surface': '0 0% 100%',
            '--surface-hover': '210 22% 93%',
            '--border': '214 20% 84%',
            '--input': '214 20% 84%',
            '--card': '0 0% 100%',
            '--card-foreground': '222 25% 12%',
            '--secondary': '210 22% 93%',
            '--secondary-foreground': '222 25% 12%',
            '--muted': '210 22% 93%',
            '--muted-foreground': '215 15% 38%',
            '--primary-foreground': '222 25% 12%',
            '--accent-foreground': '222 25% 12%',
          }
        : {
            '--background': '240 10% 4%',
            '--foreground': '0 0% 95%',
            '--surface': '240 10% 7%',
            '--surface-hover': '240 8% 12%',
            '--border': '240 8% 16%',
            '--input': '240 8% 16%',
            '--card': '240 10% 7%',
            '--card-foreground': '0 0% 95%',
            '--secondary': '240 8% 12%',
            '--secondary-foreground': '0 0% 95%',
            '--muted': '240 8% 12%',
            '--muted-foreground': '240 5% 65%',
            '--primary-foreground': '240 10% 4%',
            '--accent-foreground': '240 10% 4%',
          };

      Object.entries(variables).forEach(([property, value]) => {
        document.documentElement.style.setProperty(property, value);
      });
    };

    applyTheme();
    document.documentElement.style.setProperty('--primary', accent);
    document.documentElement.style.setProperty('--accent', accent);
    document.documentElement.style.setProperty('--gold', accent);
    document.documentElement.style.setProperty('--ring', accent);

    return undefined;
  }, [language, accent, theme]);
}
